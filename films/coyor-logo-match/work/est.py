import json
from PIL import Image
fs=json.load(open('files.json'))
# idx, sheet x, sheet y, w_thumb, sheetno
E=[(0,180,102,26),(0,177,211,26),(1,527,150,40),(3,1158,124,38),(5,1780,75,26),(5,1798,268,28),(6,205,558,52),(7,550,640,60),
(8,825,465,26),(8,845,672,28),(9,1155,550,50),(10,1525,660,62),(11,1792,488,36),(11,1815,742,38),(12,232,1045,50),(13,498,950,40),
(14,819,890,36),(14,842,1135,40),(15,1162,950,50),(16,1515,1030,60),(17,1797,925,38),(19,527,150,40),(29,1720,605,50),(30,195,1005,50),
(31,488,897,36),(31,505,1118,38),(32,868,1012,55),(33,1153,912,38),(27,1160,578,24)]
out=[]
for i,x,y,w in E:
    f=fs[i]; W,H=Image.open(f).size
    s=min(320/W,400/H)
    j=i if i<18 else i-18
    ox=(j%6)*320; oy=(j//6)*400
    if i>=18: oy=((i-18)//6)*400
    out.append(dict(file=f.split('/')[-1],cx=round((x-ox)/s),cy=round((y-oy)/s),w=round(w/s)))
json.dump(out,open('logos.json','w'),indent=1)
print(out[:3])
